#!/usr/bin/env bash
# Verificador do repo. Sai com 1 se qualquer checagem falhar. Imprime só arquivo:linha, nunca o valor achado.
cd "$(dirname "$0")/.." || exit 1
FAIL=0
fail() { echo "FALHA: $*"; FAIL=1; }

# Arquivos que o git publicaria: versionados e não ignorados (arquivo local ignorado, como .serena/, fica de fora).
FILES=$(git ls-files -co --exclude-standard | while IFS= read -r f; do [ -f "$f" ] && [ ! -L "$f" ] && echo "$f"; done | sort)
TEXT=$(for f in $FILES; do case "$f" in kernel/common/*|kernel/upstream/*) continue ;; esac; grep -Iq . "$f" 2>/dev/null && echo "$f"; done)

# V1: arquivos proibidos. kernel/common é upstream: só extensões de chave e binário, sem nomes de pasta.
PEM_OK='google_gki_ab13771415_modsign_cert.pem'
for f in $FILES; do
  case "$f" in
    ultraroot/gradle/wrapper/gradle-wrapper.jar|*/gradle/wrapper/gradle-wrapper.jar|*/$PEM_OK|$PEM_OK) continue ;;
    kernel/common/*.log|kernel/upstream/*.log) continue ;;
    *.jks|*.keystore|*.p12|*.pem|*.key|*.pass|*.apk|*.aab|*.img|*.so|*.o|*.dex|*.ap_|*.jar|*.log) fail "V1 arquivo proibido: $f"; continue ;;
  esac
  case "$f" in
    kernel/common/*|kernel/upstream/*) ;;
    keys/*|backups/*|Magisk/*|out/*|*/build/*|*/.gradle/*|*/.kotlin/*|*/.cxx/*|*/captures/*|*/.idea/*) fail "V1 pasta proibida: $f" ;;
  esac
done

# V2: segredos (só file:line; o valor nunca é impresso)
SECRET='gh[pousr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,}|AKIA[0-9A-Z]{16}|AIza[0-9A-Za-z_-]{35}|sk-[A-Za-z0-9]{20,}|-----BEGIN [A-Z ]*PRIVATE KEY-----|(storepass|keypass|password|senha)[[:space:]]*[:=][[:space:]]*[^[:space:]]{4,}'
for f in $TEXT; do
  case "$f" in tools/verify_repo.sh|kernel/lake/tools/selftest_backprop.sh) continue ;; esac  # fixture de teste do lake: token falso que testa a redação
  if grep -qE "$SECRET" "$f"; then fail "V2 segredo: $f:$(grep -nE "$SECRET" "$f" | head -n 1 | cut -d: -f1)"; fi
done

# V2b: chave privada na árvore do kernel (única checagem de segredo feita lá)
if grep -rl --exclude-dir=.git -E 'BEGIN [A-Z ]*PRIVATE KEY' kernel/common kernel/upstream 2>/dev/null | head -n 1 | grep -q .; then fail "V2 chave privada em kernel/common ou kernel/upstream"; fi

# V3: dado pessoal e caminho local. Fora da checagem: o próprio verificador, registros, regras escritas e pin upstream.
# MAC: exatamente 6 pares, sem par vizinho. Sem essa borda, a fingerprint de 32 pares do cert público casava (falso positivo).
# Linhas com o CN do cert público do GKI são ignoradas: CN, fingerprint e serial dele não são dado pessoal.
PII='[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[a-z]{2,}|(^|[^A-Za-z])(serial|Serial)[ :=]+[A-Za-z]*[0-9][A-Za-z0-9-]{4,}|adb -s [A-Za-z0-9]{8,}|\b192\.168\.[0-9]+\.[0-9]+|\b10\.[0-9]+\.[0-9]+\.[0-9]+\b|(^|[^0-9A-Fa-f:-])([0-9A-Fa-f]{2}[:-]){5}[0-9A-Fa-f]{2}([^0-9A-Fa-f:-]|$)|[Ii][Mm][Ee][Ii][^0-9]{0,12}[0-9]{15}'
PUB_CERT='Build time autogenerated kernel key'
echo 'x aa:bb:cc:dd:ee:ff y' | grep -qE "$PII" || fail "V3 teste: regex não casa MAC real"
echo 'x 76:FB:DF:D1:3F:6B:A6:12:75:6E:AE:36:E9:9F:88:50:8F:A3:20:2A:A3:51:17:70:4C:26:D5:5A:99:CC:72:A1 y' | grep -qE "$PII" && fail "V3 teste: regex casa fingerprint de 32 bytes"
LOCAL='/home/rianprei|~/superroot|~/Documentos|superroot/scratch|Documentos/mods'
for f in $TEXT; do
  case "$f" in
    tools/verify_repo.sh|AGENTS.md|docs/history/PATHMAP.md|docs/history/EXCLUSOES.txt|docs/history/REDACOES.txt|kernel/upstream/*) continue ;;
  esac
  hit=$(grep -nE "$PII" "$f" | grep -v -F "$PUB_CERT" | head -n 1)
  if [ -n "$hit" ]; then fail "V3 dado pessoal: $f:${hit%%:*}"; fi
  if grep -qE "$LOCAL" "$f"; then fail "V3 caminho local: $f:$(grep -nE "$LOCAL" "$f" | head -n 1 | cut -d: -f1)"; fi
done

# /tmp/ literal: proibido fora dos fixtures de teste do lake (exceção declarada no PATHMAP)
for f in $TEXT; do
  case "$f" in tools/verify_repo.sh|docs/history/PATHMAP.md|kernel/lake/*) continue ;; esac
  if grep -qE '(^|[ "`(=:])/tmp/' "$f"; then fail "V3 /tmp/ literal: $f"; fi
done

# V4: referências internas. Estritas nos documentos de entrada; nos históricos, só contagem de aviso
# (citam APKs, árvore do kernel e planos que ficaram fora do repo; ver docs/history/EXCLUSOES.txt).
STRICT="README.md AGENTS.md CLAUDE.md docs/README.md docs/ESTADO.md docs/PENDENCIAS-DO-DONO.md docs/ultraroot/README.md docs/ultraroot/E1-OPCOES-COPY-LAYOUT.md docs/ultrakernel/README.md kernel/README.md docs/history/TIMELINE.md"
MISSING=""
WARN=0
for f in $TEXT; do
  case "$f" in *.md|*.txt|*.sh) ;; *) continue ;; esac
  case "$f" in tools/verify_repo.sh|kernel/upstream/*) continue ;; esac
  # ERR-16: (a) o caminho começa em fronteira (não casa "dev/superroot/ultraroot/ui" no meio de outro).
  # Só fora dos STRICT (que continuam exigindo caminho exato a partir da raiz):
  # (b) referência marcada com "[fora do repo] <caminho>" (convenção em docs/history/EXCLUSOES.txt) não conta;
  # (c) arquivos de kernel/lake/ citam caminhos relativos à raiz do lake;
  # (d) caminhos do KernelSU resolvem em kernel/upstream/KernelSU/; (e) caminhos da árvore do kernel, em kernel/common/.
  strict=0; echo " $STRICT " | grep -q " $f " && strict=1
  if [ "$strict" = 1 ]; then src="$(cat "$f")"
  else src="$(sed -E 's/\[fora do repo\] (docs|ultraroot|kernel|tools)\/[A-Za-z0-9_./-]+//g' "$f")"; fi
  for p in $(printf '%s\n' "$src" | grep -oE '(^|[^A-Za-z0-9_./-])(docs|ultraroot|kernel|tools)/[A-Za-z0-9_./-]+' \
      | sed -E 's/^[^A-Za-z0-9_./-]//; s/[.,;:)]*$//' | sort -u); do
    [ -e "$p" ] && continue
    if [ "$strict" = 1 ]; then
      MISSING="$MISSING
V4 link ausente: $f -> $p"
      continue
    fi
    case "$f" in kernel/lake/*) [ -e "kernel/lake/$p" ] && continue ;; esac
    [ -e "kernel/upstream/KernelSU/$p" ] && continue
    [ -e "kernel/common/$p" ] && continue
    WARN=$((WARN+1))
  done
done
if [ -n "$MISSING" ]; then printf '%s
' "$MISSING" | sed '/^$/d'; FAIL=1; fi
echo "AVISO V4 (histórico, não bloqueia): $WARN referências a arquivos fora do repo"

# V5: pin do KernelSU: sha256 de cada arquivo = PIN.md; se o repo local do KernelSU existir, também = git show
PIN=kernel/upstream/KernelSU/PIN.md
if [ -f "$PIN" ]; then
  (cd kernel/upstream/KernelSU && grep -E '^\| [0-9a-f]{64} \|' PIN.md | awk -F'|' '{gsub(/ /,"",$2); gsub(/ /,"",$3); print $2"  "$3}' | sha256sum -c --quiet) || fail "V5 pin: sha256 não bate com PIN.md"
  K=/home/rianprei/superroot/scratch/grok/src/KernelSU; C=6e3860443f8fea7c5fc226277e53888033796488
  if [ -d "$K" ]; then
    for p in $(grep -E '^\| [0-9a-f]{64} \|' "$PIN" | awk -F'|' '{gsub(/ /,"",$3); print $3}'); do
      a=$(git -C "$K" show "$C:$p" 2>/dev/null | sha256sum | cut -d' ' -f1)
      b=$(sha256sum "kernel/upstream/KernelSU/$p" | cut -d' ' -f1)
      [ "$a" = "$b" ] || fail "V5 pin: $p difere do commit $C"
    done
  else
    echo "SKIP V5 (git show): repo local do KernelSU não existe nesta máquina"
  fi
fi

# V6: teste nativo host (12 casos PASS)
mkdir -p build
if g++ -std=c++17 -Wall -Werror -I ultraroot/core-backend/src/test/native/shim -I ultraroot/core-backend/src/main/cpp \
     ultraroot/core-backend/src/test/native/fill_test.cc -o build/fill_test 2>/dev/null; then
  n=$(./build/fill_test | grep -c ' PASS$')
  [ "$n" = 12 ] || fail "V6 teste nativo: $n PASS, esperado 12"
else
  fail "V6 teste nativo não compila"
fi

# V7: nenhum arquivo rastreado acima de 100 MB (limite do GitHub)
if git rev-parse --verify -q HEAD >/dev/null; then
  git ls-files -z | xargs -0 -r du -k | awk '$1>102400{print "V7 acima de 100 MB: "$2; bad=1} END{exit bad}' || fail "V7 arquivo grande"
fi

# V8: manifesto de integridade (se existir)
if [ -f docs/history/MANIFEST.sha256 ]; then
  sha256sum -c --quiet docs/history/MANIFEST.sha256 >/dev/null 2>&1 || fail "V8 manifesto não confere"
fi

# V9 (aviso): e-mail de autor ou committer no histórico que não é noreply. Reescrever histórico é decisão do dono (ERR-03).
MAILS=$(git log --format='%ae%n%ce' 2>/dev/null | grep '@' | grep -v 'users.noreply.github.com' | sort -u | wc -l)
[ "${MAILS:-0}" -gt 0 ] && echo "AVISO V9 (histórico): $MAILS e-mail(s) não-noreply em autor ou committer (ver docs/ERROS-PARA-REVISAO.md, ERR-03)"
if [ "$FAIL" = 0 ]; then echo "VERIFICADOR OK"; else echo "VERIFICADOR FALHOU"; fi
exit $FAIL
